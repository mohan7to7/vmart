
CREATE TABLE carts (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       user_id BIGINT,
                       guest_token_hash VARCHAR(255),

                       status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                       version BIGINT NOT NULL DEFAULT 0,

                       last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT fk_carts_user
                           FOREIGN KEY (user_id)
                               REFERENCES users(id)
                               ON DELETE CASCADE,

                       CONSTRAINT chk_carts_owner
                           CHECK (
                               (user_id IS NOT NULL AND guest_token_hash IS NULL)
                                   OR
                               (user_id IS NULL AND guest_token_hash IS NOT NULL)
                               ),

                       CONSTRAINT chk_carts_status
                           CHECK (status IN ('ACTIVE', 'CONVERTED', 'ABANDONED')),

                       CONSTRAINT chk_carts_version
                           CHECK (version >= 0)
);

CREATE UNIQUE INDEX ux_carts_one_active_per_user
    ON carts(user_id)
    WHERE user_id IS NOT NULL AND status = 'ACTIVE';

CREATE INDEX idx_carts_guest_token_hash
    ON carts(guest_token_hash)
    WHERE guest_token_hash IS NOT NULL;

CREATE INDEX idx_carts_last_activity_at
    ON carts(last_activity_at);


CREATE TABLE cart_items (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            cart_id BIGINT NOT NULL,
                            variant_id BIGINT NOT NULL,

                            quantity INTEGER NOT NULL,
                            acknowledged_price NUMERIC(12, 2),
                            price_acknowledged_at TIMESTAMPTZ,

                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_cart_items_cart
                                FOREIGN KEY (cart_id)
                                    REFERENCES carts(id)
                                    ON DELETE CASCADE,

                            CONSTRAINT fk_cart_items_variant
                                FOREIGN KEY (variant_id)
                                    REFERENCES product_variants(id),

                            CONSTRAINT uq_cart_items_cart_variant
                                UNIQUE (cart_id, variant_id),

                            CONSTRAINT chk_cart_items_quantity
                                CHECK (quantity >= 1),

                            CONSTRAINT chk_cart_items_acknowledged_price
                                CHECK (acknowledged_price IS NULL OR acknowledged_price >= 0),

                            CONSTRAINT chk_cart_items_price_acknowledgment
                                CHECK (
                                    (acknowledged_price IS NULL AND price_acknowledged_at IS NULL)
                                        OR
                                    (acknowledged_price IS NOT NULL AND price_acknowledged_at IS NOT NULL)
                                    )
);

CREATE INDEX idx_cart_items_variant_id
    ON cart_items(variant_id);


CREATE TABLE saved_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             user_id BIGINT,
                             guest_token_hash VARCHAR(255),
                             variant_id BIGINT NOT NULL,

                             notify_when_available BOOLEAN NOT NULL DEFAULT FALSE,

                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_saved_items_user
                                 FOREIGN KEY (user_id)
                                     REFERENCES users(id)
                                     ON DELETE CASCADE,

                             CONSTRAINT fk_saved_items_variant
                                 FOREIGN KEY (variant_id)
                                     REFERENCES product_variants(id),

                             CONSTRAINT chk_saved_items_owner
                                 CHECK (
                                     (user_id IS NOT NULL AND guest_token_hash IS NULL)
                                         OR
                                     (user_id IS NULL AND guest_token_hash IS NOT NULL)
                                     )
);

CREATE UNIQUE INDEX ux_saved_items_user_variant
    ON saved_items(user_id, variant_id)
    WHERE user_id IS NOT NULL;

CREATE UNIQUE INDEX ux_saved_items_guest_variant
    ON saved_items(guest_token_hash, variant_id)
    WHERE guest_token_hash IS NOT NULL;

CREATE INDEX idx_saved_items_variant_id
    ON saved_items(variant_id);